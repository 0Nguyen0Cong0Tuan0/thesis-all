        "                        label=\"▶ Tự Động Quay 360°\",\n",
        "                        method=\"animate\",\n",
        "                        args=[None, dict(\n",
        "                            frame=dict(duration=50, redraw=False),\n",
        "                            fromcurrent=True,\n",
